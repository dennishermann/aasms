// Background service worker for SMS Assistant extension

console.log('SMS Assistant service worker loaded');
try {
  importScripts('../utils/schema.js');
} catch (e) {
  console.error('Failed to load schema utils:', e);
}

const BACKEND_URL = 'http://localhost:3000';
const PYTHON_SERVICE_URL = 'http://localhost:8000'; // Python FastAPI service

// Listen for messages from popup
let pendingPDFResolutions = new Map(); // tabId -> resolve function

chrome.runtime.onMessage.addListener((request, sender, sendResponse) => {
  console.log('Service worker received message:', request);

  if (request.action === 'fetchStudies') {
    handleFetchStudies(sendResponse);
    return true;
  }

  if (request.action === 'addSource') {
    handleAddSource(request.data, sendResponse);
    return true;
  }

  if (request.action === 'resolvePDFUrl') {
    // Content script is asking us to watch for a PDF URL redirect
    // generated by an iframe it just created
    if (sender.tab) {
      console.log(`Watching for PDF redirect in tab ${sender.tab.id}...`);
      // We'll wait up to 15s for the redirect to happen
      const promise = new Promise((resolve) => {
        pendingPDFResolutions.set(sender.tab.id, resolve);
        setTimeout(() => {
          if (pendingPDFResolutions.has(sender.tab.id)) {
            pendingPDFResolutions.delete(sender.tab.id);
            resolve(null); // Timed out
          }
        }, 15000);
      });

      promise.then(url => sendResponse({ url }));
      return true; // async
    }
  }

  if (request.action === 'checkDuplicate') {
    handleCheckDuplicate(request.data, sendResponse);
    return true;
  }

  if (request.action === 'attachPdf') {
    handleAttachPdf(request.data, sendResponse);
    return true;
  }
});

// Intercept specific S3 redirects
chrome.webRequest.onBeforeRequest.addListener(
  (details) => {
    // If we see a request to the assets domain, it's likely our PDF
    if (details.url.includes('sciencedirectassets.com') && details.url.includes('.pdf')) {
      if (details.tabId !== -1 && pendingPDFResolutions.has(details.tabId)) {
        console.log('Intercepted S3 PDF URL:', details.url);
        const resolve = pendingPDFResolutions.get(details.tabId);
        pendingPDFResolutions.delete(details.tabId);
        resolve(details.url);
      }
    }
  },
  { urls: ["*://*.sciencedirectassets.com/*"] }
);

/**
 * Fetch studies from backend
 */
async function handleFetchStudies(sendResponse) {
  try {
    const response = await fetch(`${BACKEND_URL}/api/studies`);

    if (!response.ok) {
      throw new Error(`HTTP error! status: ${response.status}`);
    }

    const data = await response.json();
    sendResponse({ success: true, studies: data.data || [] });
  } catch (error) {
    console.error('Error fetching studies:', error);
    sendResponse({
      success: false,
      error: 'Failed to fetch studies. Make sure the backend is running at localhost:3000'
    });
  }
}

/**
 * Get page content from a tab
 * @param {number} tabId - Tab ID
 * @returns {Promise<string>} Page content
 */
async function getPageContent(tabId) {
  return new Promise((resolve) => {
    chrome.tabs.sendMessage(
      tabId,
      { action: 'getPageContent' },
      (response) => {
        if (chrome.runtime.lastError || !response) {
          console.warn('Failed to get page content:', chrome.runtime.lastError);
          resolve('');
          return;
        }
        resolve(response.content || '');
      }
    );
  });
}

/**
 * Extract authors using Python LLM service
 * @param {string} url - Page URL
 * @param {string} title - Page title
 * @param {string} pageContent - Page content
 * @returns {Promise<Object>} Authors and confidence
 */
async function extractAuthorsWithLLM(url, title, pageContent) {
  try {
    console.log('Calling Python LLM service for author extraction...');
    const response = await fetch(`${PYTHON_SERVICE_URL}/api/extract-authors`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        url: url,
        page_content: pageContent,
        title: title
      })
    });

    if (!response.ok) {
      console.warn('LLM author extraction failed:', response.status);
      return { authors: [], confidence: 'low' };
    }

    const data = await response.json();
    console.log('LLM extraction result:', data);
    return data;
  } catch (error) {
    console.error('Error calling LLM service:', error);
    return { authors: [], confidence: 'low' };
  }
}

